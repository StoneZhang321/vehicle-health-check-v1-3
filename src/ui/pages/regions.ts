/** 中文：保留现有中美加省州选项，地区只描述车辆市场。 English: Retain existing CN/US/CA regions as vehicle-market metadata. */
import type { Locale, Market } from "../../domain";

export interface RegionOption {
  code: string;
  label: Record<Locale, string>;
}

/** 中文：把固定三列地区表转成双语选项。 English: Convert fixed region tuples into bilingual options. */
function regions(entries: Array<[string, string, string]>): RegionOption[] {
  return entries.map(([code, zh, en]) => ({
    code,
    label: { "zh-CN": zh, en },
  }));
}

